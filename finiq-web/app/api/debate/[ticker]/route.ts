export async function GET(
  request: Request,
  props: { params: Promise<{ ticker: string }> | { ticker: string } }
) {
  const params = await props.params;
  const rawTicker = params.ticker || 'AAPL';
  const ticker = rawTicker.toUpperCase().trim();

  const apiKey = process.env.OPENAI_API_KEY;

  if (apiKey && apiKey.trim() !== '') {
    try {
      const openai = new OpenAI({ apiKey: apiKey.trim() });

      const systemPrompt = `You are the FINIQ Institutional Investment Committee, hosting a rigorous 4-agent debate on the target equity.
Simulate the following 4 roles:
1. BULL ANALYST: Strongest institutional bull thesis, aggressive catalysts, key upside drivers, and a bullish score (0-100).
2. BEAR ANALYST: Toughest institutional bear thesis, margin compression, competitive threats, downside risks, and a bearish score (0-100).
3. RISK OFFICER: Objective drawdown exposure, tail risks, beta sensitivity, and direct challenge questions for both sides.
4. CHIEF INVESTMENT STRATEGIST: High-level executive synthesis, probabilistic market outlook, actionable verdict, and formal disclaimer.

You MUST respond strictly with valid JSON matching this exact structure:
{
  "bull": {
    "thesisTitle": "string",
    "arguments": ["string", "string", "string"],
    "catalysts": ["string", "string"],
    "bullishScore": 85
  },
  "bear": {
    "thesisTitle": "string",
    "arguments": ["string", "string", "string"],
    "risks": ["string", "string"],
    "bearishScore": 60
  },
  "risk": {
    "riskLevel": "LOW | MODERATE | ELEVATED | HIGH",
    "keyRisks": ["string", "string", "string"],
    "challenges": "string evaluating central risk tension"
  },
  "chief": {
    "outlook": "string (e.g. MODERATELY BULLISH)",
    "summary": "string summarizing committee debate",
    "verdict": "string with clear strategic decision",
    "disclaimer": "This debate analysis is generated by AI prototype models and does not constitute financial advice or investment recommendations."
  }
}`;

      const userPrompt = `Provide the full institutional debate analysis for ticker: ${ticker}. Be analytical, quantitative, realistic, and specific to ${ticker}'s current business model, competitive moat, and market dynamics.`;

      // Timeout wrapper to avoid hanging
      const completionPromise = openai.chat.completions.create({
        model: 'gpt-4o-mini',
        response_format: { type: 'json_object' },
        messages: [
          { role: 'system', content: systemPrompt },
          { role: 'user', content: userPrompt },
        ],
        temperature: 0.7,
      });

      const timeoutPromise = new Promise<never>((_, reject) =>
        setTimeout(() => reject(new Error('OpenAI request timed out')), 8000)
      );

      const completion = await Promise.race([completionPromise, timeoutPromise]);
      const content = completion.choices[0]?.message?.content;

      if (content) {
        const parsed = JSON.parse(content);
        if (parsed.bull && parsed.bear && parsed.risk && parsed.chief) {
          const result: DebateOutput = {
            ticker,
            generatedAt: new Date().toISOString(),
            bull: {
              thesisTitle: parsed.bull.thesisTitle || `Bullish Case for ${ticker}`,
              arguments: Array.isArray(parsed.bull.arguments) ? parsed.bull.arguments : [],
              catalysts: Array.isArray(parsed.bull.catalysts) ? parsed.bull.catalysts : [],
              bullishScore: Number(parsed.bull.bullishScore) || 75,
              score: Number(parsed.bull.bullishScore) || 75,
              confidence: 'HIGH',
            },
            bear: {
              thesisTitle: parsed.bear.thesisTitle || `Bearish Case for ${ticker}`,
              arguments: Array.isArray(parsed.bear.arguments) ? parsed.bear.arguments : [],
              risks: Array.isArray(parsed.bear.risks) ? parsed.bear.risks : [],
              bearishScore: Number(parsed.bear.bearishScore) || 55,
              score: Number(parsed.bear.bearishScore) || 55,
              confidence: 'MODERATE',
            },
            risk: {
              riskLevel: parsed.risk.riskLevel || 'MODERATE',
              keyRisks: Array.isArray(parsed.risk.keyRisks) ? parsed.risk.keyRisks : [],
              challenges: parsed.risk.challenges || 'Balance sheet and valuation risk evaluation.',
              bullChallenges: parsed.risk.challenges || 'Growth assumptions challenge.',
              bearChallenges: parsed.risk.challenges || 'Underestimating moat challenge.',
              confidence: 'HIGH',
            },
            chief: {
              outlook: parsed.chief.outlook || 'BALANCED OUTLOOK',
              summary: parsed.chief.summary || `Synthesized multi-factor assessment for ${ticker}.`,
              verdict: parsed.chief.verdict || `Accumulate with disciplined risk management.`,
              disclaimer:
                parsed.chief.disclaimer ||
                'This debate analysis is generated by AI prototype models and does not constitute financial advice or investment recommendations. Past algorithmic analysis does not guarantee future market returns.',
              executiveSummary: parsed.chief.summary,
              keyThesis: parsed.chief.verdict,
              strongestBull: parsed.bull.arguments?.[0] || 'Strong market position.',
              strongestBear: parsed.bear.arguments?.[0] || 'Valuation and macro sensitivity.',
              areasOfConsensus: ['Execution remains paramount in coming quarters'],
            },
          };

          return NextResponse.json(result, {
            status: 200,
            headers: {
              'Cache-Control': 'public, s-maxage=60, stale-while-revalidate=120',
            },
          });
        }
      }
    } catch (err: unknown) {
      const errorMsg = err instanceof Error ? err.message : 'Unknown error';
      console.warn(`[API Debate] OpenAI debate call failed: ${errorMsg}. Falling back to curated demo debate.`);
    }
  }

  // Fallback to rich ticker-specific demo debate data
  const demoDebate = generateDemoDebate(ticker);
  return NextResponse.json(demoDebate, {
    status: 200,
    headers: {
      'Cache-Control': 'public, s-maxage=60, stale-while-revalidate=120',
    },
  });
}
